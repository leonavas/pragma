await context.addInitScript(() => {
  const intervals = new Map();
  let ticks = 0;
  const originalSet = window.setInterval;
  const originalClear = window.clearInterval;
  window.setInterval = (fn, delay, ...args) => {
    const id = originalSet(() => { ticks++; fn(...args); }, delay);
    intervals.set(id, delay);
    return id;
  };
  window.clearInterval = id => { intervals.delete(id); originalClear(id); };
  const listeners = [];
  const originalAdd = EventTarget.prototype.addEventListener;
  EventTarget.prototype.addEventListener = function (type, fn, options) {
    if (options?.signal) listeners.push({ type, signal: options.signal });
    return originalAdd.call(this, type, fn, options);
  };
  window.__lifecycle = () => ({ intervals: intervals.size, ticks, activeListeners: listeners.filter(l => !l.signal.aborted).length });
});
