import { describe, it, before, after, beforeEach, afterEach } from 'node:test'
import assert from 'node:assert/strict'
import { browsers, launch, start, timers } from './app.mjs'

const PORT = Number(process.env.PORT ?? 5281)
let app

before(async () => { app = await start('serve', PORT) })
after(() => app?.stop())

for (const nome of browsers) {
  describe(`${nome} (pragma serve)`, () => {
    let browser, ctx, page, erros

    before(async () => { browser = await launch(nome) })
    after(() => browser?.close())
    beforeEach(async () => {
      ctx = await browser.newContext({ baseURL: app.url })
      await ctx.addInitScript(timers)
      page = await ctx.newPage()
      erros = []
      page.on('pageerror', e => erros.push(e.message))
    })
    afterEach(async () => {
      await ctx.close()
      assert.deepEqual(erros, [])
    })

    const nav = nome => page.getByRole('banner').getByRole('link', { name: nome, exact: true })
    const h1 = () => page.locator('main h1').first().textContent()
    const esperarH1 = texto => page.waitForFunction(t => document.querySelector('main h1')?.textContent === t, texto)
    const marcar = () => page.evaluate(() => { self.__marca = 1 })
    const semRecarregar = async () => assert.equal(await page.evaluate(() => self.__marca), 1)
    const carrinho = () => page.getByRole('banner').getByRole('link', { name: /Carrinho/ }).locator('span')
    const produtos = () => page.locator('main a[href^="/loja/"]')

    it('navega pelas páginas sem recarregar, com título e aria-current', async () => {
      await page.goto('/')
      await marcar()
      assert.equal(await nav('Painel').getAttribute('aria-current'), 'page')
      await nav('Tarefas').click()
      await page.waitForFunction(() => document.title === 'Tarefas · Mercadinho')
      assert.equal(await h1(), 'Tarefas')
      assert.equal(await nav('Tarefas').getAttribute('aria-current'), 'page')
      assert.equal(await nav('Painel').getAttribute('aria-current'), null)
      await nav('Loja').click()
      await produtos().first().waitFor()
      await produtos().first().click()
      await esperarH1('Café torrado 500 g')
      await page.getByRole('link', { name: '← Voltar para a loja' }).click()
      await esperarH1('Loja')
      await page.goBack()
      await esperarH1('Café torrado 500 g')
      await page.goForward()
      await esperarH1('Loja')
      await semRecarregar()
      const r = await page.goto('/nao-existe')
      assert.equal(r.status(), 404)
      assert.equal(await h1(), 'Página não encontrada')
    })

    it('prefetch no hover baixa o HTML da rota antes do clique', async () => {
      await page.goto('/')
      const html = page.waitForRequest(r => r.url().endsWith('/tarefas/index.html'))
      await nav('Tarefas').hover()
      await html
    })

    it('deep link e refresh em /loja/cafe com SSR', async () => {
      const semJs = await browser.newContext({ baseURL: app.url, javaScriptEnabled: false })
      const p = await semJs.newPage()
      await p.goto('/loja/cafe')
      assert.equal(await p.locator('main h1').textContent(), 'Café torrado 500 g')
      assert.equal(await p.locator('main').getByText('R$ 32,90').count(), 1)
      await semJs.close()

      const dados = []
      page.on('request', r => r.url().includes('/_data/') && dados.push(r.url()))
      await page.goto('/loja/cafe')
      await page.reload()
      assert.equal(await h1(), 'Café torrado 500 g')
      await page.getByRole('button', { name: 'Adicionar' }).click()
      assert.equal(await carrinho().textContent(), '1')
      assert.deepEqual(dados, [])
      await page.goto('/loja/nao-tem')
      assert.equal(await h1(), 'Produto não encontrado')
    })

    it('loja mostra skeleton e depois os dados; filtros na URL; erro com ?falhar=1', async () => {
      await page.goto('/loja', { waitUntil: 'commit' })
      await page.locator('main .skeleton').first().waitFor()
      assert.equal(await page.locator('main .skeleton').count(), 4)
      await produtos().nth(8).waitFor()
      assert.equal(await page.locator('main .skeleton').count(), 0)
      assert.equal(await page.getByText('Esgotado', { exact: true }).locator('visible=true').count(), 1)

      await marcar()
      await page.getByRole('link', { name: 'Limpeza' }).click()
      await page.waitForURL('**/loja?categoria=limpeza')
      await page.waitForFunction(() => document.querySelectorAll('main a[href^="/loja/"]').length === 3)
      assert.equal(await page.getByRole('link', { name: 'Limpeza' }).getAttribute('aria-current'), 'true')
      await page.getByRole('searchbox', { name: 'Buscar produto' }).fill('sab')
      assert.equal(await produtos().count(), 1)
      await page.getByRole('searchbox', { name: 'Buscar produto' }).fill('zzz')
      await page.getByText('Nenhum produto').waitFor()
      await semRecarregar()

      await page.goto('/loja?falhar=1')
      await page.getByRole('alert').getByText('Não foi possível carregar os produtos.').waitFor()
      await page.getByRole('link', { name: 'Tentar de novo' }).click()
      await produtos().nth(8).waitFor()
    })

    it('carrinho: quantidade, estoque, badge, resumo e esvaziar com confirmação', async () => {
      await page.goto('/loja')
      const alface = page.locator('main li').filter({ has: page.locator('a[href="/loja/alface"]') })
      await alface.waitFor()
      const mais = alface.getByRole('button', { name: 'Aumentar quantidade' })
      await mais.click()
      await mais.click()
      assert.equal(await mais.isDisabled(), true)
      await alface.getByRole('button', { name: 'Adicionar' }).click()
      assert.equal(await carrinho().textContent(), '3')
      assert.equal(await alface.locator('output').textContent(), '1')
      const resumo = page.getByRole('complementary')
      assert.equal(await resumo.getByRole('button', { name: 'Aumentar' }).isDisabled(), true)
      await resumo.getByRole('button', { name: 'Diminuir' }).click()
      assert.equal(await carrinho().textContent(), '2')
      assert.match(await resumo.textContent(), /R\$\s9,00/)
      assert.equal(await page.locator('main li').filter({ has: page.locator('a[href="/loja/detergente"]') }).getByRole('button', { name: 'Adicionar' }).isDisabled(), true)

      await resumo.getByRole('button', { name: 'Esvaziar' }).click()
      const alerta = page.getByRole('alertdialog', { name: 'Esvaziar o carrinho?' })
      await alerta.getByRole('button', { name: 'Cancelar' }).click()
      assert.equal(await carrinho().textContent(), '2')
      await resumo.getByRole('button', { name: 'Esvaziar' }).click()
      await alerta.getByRole('button', { name: 'Esvaziar' }).click()
      await carrinho().filter({ hasText: /^0$/ }).waitFor()
      await resumo.getByText('Carrinho vazio.').waitFor()
    })

    it('Painel: indicadores refletem carrinho e tarefas; contadores independentes com limites', async () => {
      await page.goto('/loja')
      await produtos().first().waitFor()
      await page.locator('main li').first().getByRole('button', { name: 'Adicionar' }).click()
      await nav('Painel').click()
      const valor = titulo => page.locator('[data-c="indicador"]').filter({ has: page.getByRole('heading', { name: titulo }) }).locator('p').first()
      await page.getByRole('heading', { name: 'Itens no carrinho' }).waitFor()
      assert.equal(await valor('Itens no carrinho').textContent(), '1')
      assert.match(await valor('Total do carrinho').textContent(), /R\$\s32,90/)
      assert.equal(await valor('Tarefas pendentes').textContent(), '2')

      const grupo = nome => page.getByRole('group', { name: nome, exact: true })
      const pulos = grupo('Pulos de 5')
      for (let i = 0; i < 8; i++) await pulos.getByRole('button', { name: 'Aumentar Pulos de 5' }).click()
      assert.equal(await pulos.locator('output').textContent(), '50')
      assert.equal(await pulos.getByRole('button', { name: 'Aumentar Pulos de 5' }).isDisabled(), true)
      await grupo('Cliques').getByRole('button', { name: 'Aumentar Cliques' }).click()
      assert.equal(await grupo('Cliques').locator('output').textContent(), '1')
      for (let i = 0; i < 10; i++) await pulos.getByRole('button', { name: 'Diminuir Pulos de 5' }).click()
      assert.equal(await pulos.locator('output').textContent(), '0')
      assert.equal(await pulos.getByRole('button', { name: 'Diminuir Pulos de 5' }).isDisabled(), true)

      await page.getByRole('tab', { name: 'Sobre' }).focus()
      await page.keyboard.press('ArrowRight')
      await page.keyboard.press('ArrowRight')
      assert.equal(await page.evaluate(() => document.activeElement.textContent), 'Contador')
      assert.equal(await page.getByRole('tab', { name: 'Contador' }).getAttribute('aria-selected'), 'true')
      assert.equal(await grupo('Na aba').locator('output').textContent(), '3')
      await grupo('Na aba').getByRole('button', { name: 'Aumentar Na aba' }).click()
      assert.equal(await grupo('Na aba').locator('output').textContent(), '6')
      assert.equal(await grupo('Cliques').locator('output').textContent(), '1')
      await page.getByRole('tab', { name: 'Contador' }).focus()
      await page.keyboard.press('ArrowLeft')
      assert.equal(await page.getByRole('tab', { name: 'Atalhos' }).getAttribute('aria-selected'), 'true')
    })

    it('tarefas: adicionar, validar, concluir, editar, remover, buscar, filtrar e limpar', async () => {
      await page.goto('/tarefas')
      const campo = page.getByRole('textbox', { name: 'Nova tarefa' })
      const itens = page.locator('main ul li')
      const erro = page.locator('#erro-tarefa')
      const contar = n => page.waitForFunction(n => document.querySelectorAll('main ul li').length === n, n)
      await campo.fill('ab')
      await campo.press('Enter')
      assert.equal(await erro.textContent(), 'Use ao menos 3 caracteres.')
      await campo.fill('comprar CAFÉ')
      await campo.press('Enter')
      assert.equal(await erro.textContent(), 'Essa tarefa já existe.')
      await campo.fill('Comprar pão')
      await campo.press('Enter')
      assert.equal(await erro.textContent(), '')
      assert.equal(await campo.inputValue(), '')
      assert.equal(await page.evaluate(() => document.activeElement.id), 'nova-tarefa')
      await contar(4)

      await page.getByRole('checkbox', { name: 'Comprar pão' }).check()
      assert.equal(await page.locator('[data-c="indicador"] p').first().textContent(), '2 de 4')

      await page.getByText('Ligar para a farmácia').dblclick()
      const edicao = page.getByRole('textbox', { name: 'Editar tarefa' })
      assert.equal(await page.evaluate(() => document.activeElement.getAttribute('aria-label')), 'Editar tarefa')
      await edicao.fill('Ligar para o médico')
      await edicao.press('Enter')
      await page.getByText('Ligar para o médico').waitFor()
      await page.getByText('Ligar para o médico').dblclick()
      await edicao.fill('Outra coisa')
      await edicao.press('Escape')
      await page.getByText('Ligar para o médico').waitFor()

      await page.getByRole('button', { name: 'Remover Ligar para o médico' }).click()
      await contar(3)
      await page.getByRole('searchbox', { name: 'Buscar tarefa' }).fill('PAG')
      await contar(1)
      await page.getByRole('searchbox', { name: 'Buscar tarefa' }).fill('')

      await page.getByRole('link', { name: 'Pendentes' }).click()
      await page.waitForURL('**/tarefas?filtro=pendentes')
      await contar(1)
      await page.getByRole('link', { name: 'Concluídas' }).click()
      await page.waitForURL('**/tarefas?filtro=concluidas')
      await contar(2)
      await page.goBack()
      await page.waitForURL('**/tarefas?filtro=pendentes')
      await contar(1)
      await page.reload()
      await contar(1)
      assert.equal(await page.getByRole('link', { name: 'Pendentes' }).getAttribute('aria-current'), 'true')
      await page.getByRole('checkbox').click()
      await itens.getByText('Nenhuma tarefa').waitFor()

      await page.getByRole('link', { name: 'Todas' }).click()
      await page.waitForURL('**/tarefas?filtro=todas')
      await page.getByRole('button', { name: 'Ações' }).click()
      await page.getByRole('button', { name: 'Limpar concluídas…' }).click()
      const alerta = page.getByRole('alertdialog', { name: 'Limpar concluídas?' })
      await alerta.getByRole('button', { name: 'Cancelar' }).click()
      await contar(3)
      await page.getByRole('button', { name: 'Ações' }).click()
      await page.getByRole('button', { name: 'Limpar concluídas…' }).click()
      await alerta.getByRole('button', { name: 'Limpar' }).click()
      await itens.getByText('Nenhuma tarefa').waitFor()
    })

    it('modal: voltar fecha sem navegar, Esc devolve o foco, scroll travado sem salto', async () => {
      await page.goto('/')
      await marcar()
      const largura = () => page.evaluate(() => document.body.getBoundingClientRect().width)
      const antes = await largura()
      const sobre = page.getByRole('button', { name: 'Sobre o app' })
      const modal = page.getByRole('dialog', { name: 'Sobre o Mercadinho' })
      await sobre.click()
      await modal.waitFor()
      assert.equal(await page.evaluate(() => document.documentElement.hasAttribute('data-scroll-lock')), true)
      assert.equal(await page.evaluate(() => getComputedStyle(document.documentElement).overflow), 'hidden')
      assert.equal(await largura(), antes)
      await page.goBack()
      await modal.waitFor({ state: 'hidden' })
      assert.equal(new URL(page.url()).pathname, '/')
      await page.waitForFunction(() => !document.documentElement.hasAttribute('data-scroll-lock'))
      await sobre.click()
      await page.keyboard.press('Escape')
      await modal.waitFor({ state: 'hidden' })
      assert.equal(await page.evaluate(() => document.activeElement.textContent), 'Sobre o app')
      await semRecarregar()

      await page.setViewportSize({ width: 800, height: 300 })
      await page.evaluate(() => scrollTo(0, 200))
      const antes2 = await largura()
      await page.evaluate(() => document.querySelector('[data-open="sobre"]').click())
      await page.mouse.wheel(0, 400)
      await page.waitForTimeout(100)
      assert.equal(await page.evaluate(() => scrollY), 200)
      assert.equal(await largura(), antes2)
      await modal.getByRole('button', { name: 'Fechar', exact: true }).last().click()
      assert.equal(await page.evaluate(() => scrollY), 200)
    })

    it('refresh mantém tarefas, carrinho e tema (sem piscar)', async () => {
      await page.goto('/loja')
      await produtos().first().waitFor()
      await page.locator('main li').first().getByRole('button', { name: 'Adicionar' }).click()
      await nav('Tarefas').click()
      await page.getByRole('textbox', { name: 'Nova tarefa' }).fill('Persistir')
      await page.getByRole('textbox', { name: 'Nova tarefa' }).press('Enter')
      await nav('Painel').click()
      await page.getByRole('button', { name: 'Tema escuro' }).click()
      assert.equal(await page.evaluate(() => document.documentElement.dataset.theme), 'dark')
      await page.reload()
      assert.equal(await carrinho().textContent(), '1')
      assert.equal(await page.getByRole('button', { name: 'Tema claro' }).getAttribute('aria-pressed'), 'true')
      await page.goto('/tarefas')
      await page.getByText('Persistir').waitFor()

      await page.route('**/assets/**/*.js', r => r.abort())
      await page.goto('/')
      assert.equal(await page.evaluate(() => document.documentElement.dataset.theme), 'dark')
      assert.notEqual(await page.evaluate(() => getComputedStyle(document.documentElement).backgroundColor), 'rgb(255, 255, 255)')
    })

    it('o timer do relógio para ao sair do Painel', async () => {
      await page.goto('/')
      const hora = await page.locator('main time').textContent()
      assert.match(hora, /^\d\d:\d\d:\d\d$/)
      await page.waitForFunction(h => document.querySelector('main time').textContent !== h, hora)
      assert.equal(await page.evaluate(() => __timers()), 1)
      await nav('Tarefas').click()
      await page.waitForFunction(() => document.title.startsWith('Tarefas'))
      assert.equal(await page.evaluate(() => __timers()), 0)
      await nav('Painel').click()
      await page.locator('main time').waitFor()
      assert.equal(await page.evaluate(() => __timers()), 1)
    })

    it('action de servidor via ctx.call e logs OTel do cliente em /_otel', async () => {
      await page.goto('/loja/banana')
      const curtidas = page.locator('main [data-text="data.produto.curtidas"]')
      const antes = Number(await curtidas.textContent())
      const acao = page.waitForResponse(r => r.url().endsWith('/_action/loja/banana/curtir'))
      await page.getByRole('button', { name: 'Gostei' }).click()
      assert.equal((await acao).status(), 200)
      await page.waitForFunction(n => Number(document.querySelector('main [data-text="data.produto.curtidas"]').textContent) === n, antes + 1)
      assert.ok((await acao).request().headers().traceparent)

      const otel = page.waitForRequest(r => r.url().endsWith('/_otel') && r.postData()?.includes('produto adicionado ao carrinho'))
      await page.getByRole('button', { name: 'Adicionar' }).click()
      const lote = JSON.parse((await otel).postData())
      const registro = lote.logs.find(l => l.body === 'produto adicionado ao carrinho')
      assert.equal(registro.severityText, 'INFO')
      assert.equal(registro.attributes['produto.id'], 'banana')
      await page.waitForTimeout(200)
      assert.match(app.log(), /produto curtido/)
    })

    it('cada página pré-carrega só o que a primeira pintura usa', async () => {
      const preloads = async url => (await (await fetch(app.url + url)).text()).match(/rel="modulepreload" href="[^"]+"/g).map(s => s.split('/assets/')[1].replace(/-[0-9a-f]{8}\.js"$/, ''))
      const painel = await preloads('/')
      assert.ok(painel.includes('core/overlay') && painel.includes('lib/components/relogio/relogio'))
      assert.ok(!painel.some(m => m.startsWith('routes/loja')))
      const loja = await preloads('/loja')
      assert.ok(!loja.includes('lib/components/relogio/relogio') && !loja.includes('core/theme'))
      const nf = await (await fetch(app.url + '/_404.html')).text()
      assert.ok(!nf.includes('overlay-'))
    })
  })
}
